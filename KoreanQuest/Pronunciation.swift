import Foundation

/// 朗读修正表
///
/// 之前 `Speech.speak(item.korean)` 是直接把「字面上写的韩语」丢给 TTS，
/// 于是很多地方读出来的根本不是那个词的实际读法：
///
/// - 单个字母 ㄱ / ㅏ：TTS 要么读不出声，要么读成字母名「기역」
/// - 笑声和表情 ㅋㅋㅋ / ㅎㅎ / ㅠㅠ：韩国人说话时读的是 크크크 / 흐흐，
///   直接读字母完全不是那回事
/// - 音变词 한국어 / 좋아 / 같이：拼写是 한국어，实际说的是 한구거；
///   옷을 说的是 오슬，맛있다 说的是 마싣따
/// - 聊天缩写 ㅇㅇ / ㅇㅋ / ㅂㅂ：只打了初声，读出来得是 응응 / 오케이 / 바이바이
///
/// 这里统一给出「TTS 应该念的写法」，朗读时先查表，查不到才退回原词。
enum Pronunciation {

    static let map: [String: String] = [

        // MARK: 第 1 关 基础辅音
        // 辅音自己发不出声，用「辅音 + ㅏ」的示范音节，听到的就是这个辅音的真实音色
        "ㄱ": "가", "ㄴ": "나", "ㄷ": "다", "ㄹ": "라", "ㅁ": "마",
        "ㅂ": "바", "ㅅ": "사", "ㅇ": "아", "ㅈ": "자", "ㅎ": "하",

        // MARK: 第 2 关 基础元音
        "ㅏ": "아", "ㅓ": "어", "ㅗ": "오", "ㅜ": "우", "ㅡ": "으", "ㅣ": "이",

        // MARK: 第 3 关 复合元音
        "ㅑ": "야", "ㅕ": "여", "ㅛ": "요", "ㅠ": "유",
        "ㅐ": "애", "ㅔ": "에",
        "ㅘ": "와", "ㅝ": "워", "ㅙ": "왜", "ㅞ": "웨", "ㅚ": "외",
        "ㅟ": "위", "ㅢ": "의",

        // MARK: 第 4 关 紧音 + 送气音
        "ㄲ": "까", "ㄸ": "따", "ㅃ": "빠", "ㅆ": "싸", "ㅉ": "짜",
        "ㅋ": "카", "ㅌ": "타", "ㅍ": "파", "ㅊ": "차",

        // MARK: 第 6 关 双收音（写两个读一个，听发音要听实际读音）
        "닭": "닥", "값": "갑", "없다": "업따", "앉다": "안따",
        "여덟": "여덜", "삶": "삼", "읊다": "읍따",

        // MARK: 第 8 关 笑声 / 表情
        "ㅋㅋㅋ": "크크크", "ㅎㅎ": "흐흐",

        // MARK: 第 9 关 音变规则（拼写 → 实际发音）
        "한국어": "한구거",
        "좋아": "조아",
        "같이": "가치",
        "꽃": "꼳",
        "옷을": "오슬",
        "맛있다": "마싣따",
        "없어": "업써",
        "어떻게": "어떠케",
        "괜찮아": "괜차나",
        "멋있다": "머싣따",
        "좋겠다": "조겓따",

        // MARK: 第 14 关 聊天缩略语（只读初声等于没读）
        "ㅇㅇ": "응응",
        "ㅇㅋ": "오케이",
        "ㅂㅂ": "바이바이",
        "ㄱㄱ": "고고",
        "ㄴㄴ": "노노",
        "ㅈㅅ": "죄송",
        "ㅁㄹ": "몰라",
        "ㅇㅈ": "인정",
        "ㅅㄱ": "수고",
        "ㅊㅋ": "축하",
        "ㄷㄷ": "덜덜",
        "ㅠㅠ": "엉엉",
        "ㅡㅡ": "으으",
        "ㄹㅇ": "레알",
        "ㅁㅊ": "미친"
    ]

    /// 传给 TTS 的文本：有修正就用修正，没有就原样读
    static func text(for korean: String) -> String {
        map[korean] ?? korean
    }

    /// 读的和写的不一样时，界面上要标出来，不然会以为 App 读错了
    static func differs(_ korean: String) -> Bool {
        text(for: korean) != korean
    }
}
